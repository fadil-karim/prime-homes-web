/* Prime Homes - site behaviour. Plain JavaScript, no dependencies.
   Property data comes from /assets/js/properties.js (generated by tools/render.py). */
(function () {
  'use strict';

  var EMAIL = 'info@primehomesuk.com';
  var DATA = window.PRIME_PROPERTIES || [];

  function $(sel, ctx) { return (ctx || document).querySelector(sel); }
  function $$(sel, ctx) { return Array.prototype.slice.call((ctx || document).querySelectorAll(sel)); }
  function esc(s) {
    return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }
  function icon(name) {
    return '<svg class="icon" aria-hidden="true"><use href="/assets/img/icons.svg#' + name + '"></use></svg>';
  }
  function toInt(v) {
    var n = parseInt(String(v || '').replace(/[^0-9]/g, ''), 10);
    return isNaN(n) ? null : n;
  }
  function debounce(fn, ms) {
    var t;
    return function () { clearTimeout(t); t = setTimeout(fn, ms); };
  }

  /* ---------- Header navigation ---------- */
  var header = $('.site-header');
  var navToggle = $('.nav-toggle');
  if (header && navToggle) {
    navToggle.addEventListener('click', function () {
      var open = header.classList.toggle('is-open');
      navToggle.setAttribute('aria-expanded', open ? 'true' : 'false');
    });
    document.addEventListener('click', function (e) {
      if (header.classList.contains('is-open') && !header.contains(e.target)) {
        header.classList.remove('is-open');
        navToggle.setAttribute('aria-expanded', 'false');
      }
    });
  }
  $$('[data-year]').forEach(function (el) { el.textContent = String(new Date().getFullYear()); });

  /* ---------- Property cards (markup mirrors tools/render.py) ---------- */
  function badge(p) {
    if (p.status === 'let') return '<span class="badge let">Let</span>';
    if (p.status === 'sold') return '<span class="badge sold">Sold</span>';
    return p.market === 'sales' ? '<span class="badge sale">For sale</span>' : '<span class="badge rent">To rent</span>';
  }
  function plural(n, word) { return n + ' ' + word + (n === 1 ? '' : 's'); }
  function card(p) {
    var img = p.thumb || p.images[0];
    var specs = [];
    if (p.beds) specs.push('<span>' + icon('bed') + plural(p.beds, 'bed') + '</span>');
    if (p.baths) specs.push('<span>' + icon('bath') + plural(p.baths, 'bath') + '</span>');
    if (p.receptions) specs.push('<span>' + icon('sofa') + plural(p.receptions, 'reception') + '</span>');
    if (p.type) specs.push('<span>' + icon('tag') + esc(p.type) + '</span>');
    return '<a class="prop-card" href="/property/' + esc(p.slug) + '">' +
      '<div class="prop-media"><img src="/assets/img/' + esc(img) + '.jpg" alt="' + esc(p.title) + '" loading="lazy" width="640" height="480">' + badge(p) +
      '<span class="badge-count">' + icon('camera') + p.images.length + '</span></div>' +
      '<div class="prop-body"><div class="prop-price">' + esc(p.priceLabel) + '</div>' +
      '<h3 class="prop-title">' + esc(p.title) + '</h3>' +
      '<div class="prop-area">' + icon('pin') + esc(p.area) + '</div>' +
      (p.summary ? '<p class="prop-summary">' + esc(p.summary) + '</p>' : '') +
      '<div class="specs">' + specs.join('') + '</div></div></a>';
  }

  /* ---------- Home page search ---------- */
  var homeSearch = $('#home-search');
  if (homeSearch) {
    homeSearch.addEventListener('submit', function (e) {
      e.preventDefault();
      var f = homeSearch.elements;
      var category = f.category.value;
      var market = category.indexOf('sales') > -1 ? 'sales' : 'lettings';
      var q = new URLSearchParams();
      q.set('cat', category.indexOf('commercial') === 0 ? 'commercial' : 'residential');
      if (f.q.value.trim()) q.set('q', f.q.value.trim());
      if (toInt(f.min_price.value) !== null) q.set('min_price', String(toInt(f.min_price.value)));
      if (toInt(f.beds_min.value) !== null) q.set('beds_min', String(toInt(f.beds_min.value)));
      window.location.href = '/' + market + '?' + q.toString();
    });
  }

  /* ---------- Listing pages: filter, sort, URL sync ---------- */
  var listing = $('[data-listing]');
  if (listing) {
    var market = listing.getAttribute('data-listing');
    var form = $('#filters');
    var results = $('#results');
    var countEl = $('#results-count');
    var sortSel = $('#sort');
    var FIELDS = ['q', 'cat', 'min_price', 'max_price', 'beds_min', 'beds_max', 'baths_min', 'baths_max', 'rec_min', 'rec_max', 'type'];
    var params = new URLSearchParams(window.location.search);
    FIELDS.forEach(function (k) {
      if (params.has(k) && form.elements[k]) form.elements[k].value = params.get(k);
    });
    if (params.has('loc') && form.elements.q) form.elements.q.value = params.get('loc');
    if (params.has('sort') && sortSel) sortSel.value = params.get('sort');
    (params.get('features') || '').split(',').forEach(function (name) {
      $$('input[name="feature"]', form).forEach(function (box) { if (box.value === name) box.checked = true; });
    });

    var apply = function (syncUrl) {
      var f = form.elements;
      var q = (f.q.value || '').trim().toLowerCase();
      var cat = f.cat ? f.cat.value : '';
      var minP = toInt(f.min_price.value), maxP = toInt(f.max_price.value);
      var bMin = toInt(f.beds_min.value), bMax = toInt(f.beds_max.value);
      var baMin = toInt(f.baths_min.value), baMax = toInt(f.baths_max.value);
      var rMin = toInt(f.rec_min.value), rMax = toInt(f.rec_max.value);
      var type = f.type.value;
      var feats = $$('input[name="feature"]:checked', form).map(function (i) { return i.value; });
      var list = DATA.filter(function (p) {
        if (p.market !== market || p.status !== 'available') return false;
        if (cat && p.category !== cat) return false;
        if (q && (p.title + ' ' + p.area + ' ' + (p.postcode || '')).toLowerCase().indexOf(q) === -1) return false;
        if (minP !== null && p.price < minP) return false;
        if (maxP !== null && p.price > maxP) return false;
        if (bMin !== null && (p.beds || 0) < bMin) return false;
        if (bMax !== null && (p.beds || 0) > bMax) return false;
        if (baMin !== null && (p.baths || 0) < baMin) return false;
        if (baMax !== null && (p.baths || 0) > baMax) return false;
        if (rMin !== null && (p.receptions || 0) < rMin) return false;
        if (rMax !== null && (p.receptions || 0) > rMax) return false;
        if (type && p.type !== type) return false;
        for (var i = 0; i < feats.length; i++) {
          if ((p.features || []).indexOf(feats[i]) === -1) return false;
        }
        return true;
      });
      var sort = sortSel ? sortSel.value : '';
      if (sort === 'price_max') list.sort(function (a, b) { return b.price - a.price; });
      if (sort === 'price_min') list.sort(function (a, b) { return a.price - b.price; });
      results.innerHTML = list.length ? list.map(card).join('') :
        '<div class="empty"><h3>No properties match those filters</h3>' +
        '<p>Try widening the price range or clearing a few options. New listings are added regularly, so do check back or <a href="/contact">tell us what you are looking for</a>.</p>' +
        '<button type="button" class="btn btn-outline btn-sm" data-reset>Clear filters</button></div>';
      countEl.textContent = list.length + (list.length === 1 ? ' property' : ' properties');
      if (syncUrl) {
        var u = new URLSearchParams();
        FIELDS.forEach(function (k) {
          if (f[k] && String(f[k].value).trim()) u.set(k, String(f[k].value).trim());
        });
        if (feats.length) u.set('features', feats.join(','));
        if (sort) u.set('sort', sort);
        var qs = u.toString();
        window.history.replaceState(null, '', window.location.pathname + (qs ? '?' + qs : ''));
      }
    };
    form.addEventListener('submit', function (e) { e.preventDefault(); apply(true); });
    form.addEventListener('input', debounce(function () { apply(true); }, 250));
    form.addEventListener('change', function (e) {
      if (e.target.tagName === 'SELECT' || e.target.type === 'checkbox') apply(true);
    });
    if (sortSel) sortSel.addEventListener('change', function () { apply(true); });
    document.addEventListener('click', function (e) {
      if (e.target.closest('[data-reset]')) { form.reset(); if (sortSel) sortSel.value = ''; apply(true); }
    });
    var filtersToggle = $('.filters-toggle');
    if (filtersToggle) {
      filtersToggle.addEventListener('click', function () {
        var open = form.classList.toggle('is-open');
        filtersToggle.setAttribute('aria-expanded', open ? 'true' : 'false');
      });
    }
    apply(false);
  }

  /* ---------- Property gallery and lightbox ---------- */
  var lightbox = $('.lightbox');
  function closeLightbox() {
    if (lightbox && lightbox.classList.contains('is-open')) {
      lightbox.classList.remove('is-open');
      document.body.classList.remove('no-scroll');
    }
  }
  var gallery = $('[data-gallery]');
  if (gallery && lightbox) {
    var images = JSON.parse(gallery.getAttribute('data-gallery'));
    var mainImg = $('.gallery-main img', gallery);
    var thumbs = $$('.thumbs button', gallery);
    var lbImg = $('img', lightbox);
    var lbCount = $('.lb-count', lightbox);
    var current = 0;
    var show = function (i) {
      current = (i + images.length) % images.length;
      mainImg.src = '/assets/img/' + images[current] + '.jpg';
      thumbs.forEach(function (b, j) { b.classList.toggle('is-active', j === current); });
    };
    var openLightbox = function (i) {
      show(i);
      lbImg.src = mainImg.src;
      lbImg.alt = mainImg.alt;
      lbCount.textContent = (current + 1) + ' / ' + images.length;
      lightbox.classList.add('is-open');
      document.body.classList.add('no-scroll');
    };
    thumbs.forEach(function (b, i) { b.addEventListener('click', function () { show(i); }); });
    $('.gallery-main', gallery).addEventListener('click', function () { openLightbox(current); });
    $('.lb-close', lightbox).addEventListener('click', closeLightbox);
    $('.lb-prev', lightbox).addEventListener('click', function (e) { e.stopPropagation(); openLightbox(current - 1); });
    $('.lb-next', lightbox).addEventListener('click', function (e) { e.stopPropagation(); openLightbox(current + 1); });
    lightbox.addEventListener('click', function (e) { if (e.target === lightbox) closeLightbox(); });
    document.addEventListener('keydown', function (e) {
      if (!lightbox.classList.contains('is-open')) return;
      if (e.key === 'ArrowLeft') openLightbox(current - 1);
      if (e.key === 'ArrowRight') openLightbox(current + 1);
    });
  }

  /* ---------- Modal (request a viewing) ---------- */
  var modal = $('#viewing-modal');
  function closeModal() {
    if (modal && modal.classList.contains('is-open')) {
      modal.classList.remove('is-open');
      document.body.classList.remove('no-scroll');
    }
  }
  if (modal) {
    $$('[data-open-modal]').forEach(function (b) {
      b.addEventListener('click', function () {
        modal.classList.add('is-open');
        document.body.classList.add('no-scroll');
        var first = modal.querySelector('input, select');
        if (first) first.focus();
      });
    });
    modal.addEventListener('click', function (e) { if (e.target === modal) closeModal(); });
    $$('.modal-close', modal).forEach(function (b) { b.addEventListener('click', closeModal); });
  }
  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape') {
      closeModal();
      closeLightbox();
      if (header) { header.classList.remove('is-open'); if (navToggle) navToggle.setAttribute('aria-expanded', 'false'); }
    }
  });

  /* ---------- Forms: open the visitor's email app with the enquiry filled in ---------- */
  $$('form[data-mailto]').forEach(function (form) {
    form.addEventListener('submit', function (e) {
      e.preventDefault();
      if (typeof form.checkValidity === 'function' && !form.checkValidity()) {
        if (typeof form.reportValidity === 'function') form.reportValidity();
        return;
      }
      var lines = [];
      $$('input, select, textarea', form).forEach(function (el) {
        if (!el.name || el.type === 'submit' || el.type === 'button' || el.type === 'hidden') return;
        if ((el.type === 'radio' || el.type === 'checkbox') && !el.checked) return;
        var label = el.getAttribute('data-label') || el.name;
        var value = el.type === 'checkbox' ? 'Yes' : String(el.value || '').trim();
        if (el.tagName === 'SELECT' && el.selectedIndex > -1) value = el.options[el.selectedIndex].text.trim();
        if (el.type === 'radio') value = el.getAttribute('data-value') || value;
        if (!value) return;
        lines.push(label + ': ' + value);
      });
      var subject = form.getAttribute('data-subject') || 'Website enquiry';
      var intro = form.getAttribute('data-intro');
      var body = (intro ? [intro, ''] : []).concat(lines).join('\r\n');
      window.location.href = 'mailto:' + EMAIL + '?subject=' + encodeURIComponent(subject) + '&body=' + encodeURIComponent(body);
      var note = form.querySelector('.form-note');
      if (note) note.classList.add('is-visible');
    });
  });

  /* ---------- Share links ---------- */
  var shareLinks = $$('[data-share]');
  if (shareLinks.length) {
    var u = encodeURIComponent(window.location.href);
    var t = encodeURIComponent(document.title);
    var targets = {
      facebook: 'https://www.facebook.com/sharer/sharer.php?u=' + u,
      x: 'https://twitter.com/intent/tweet?url=' + u + '&text=' + t,
      linkedin: 'https://www.linkedin.com/sharing/share-offsite/?url=' + u,
      whatsapp: 'https://wa.me/?text=' + t + '%20' + u,
      email: 'mailto:?subject=' + t + '&body=' + u
    };
    shareLinks.forEach(function (a) {
      var key = a.getAttribute('data-share');
      if (!targets[key]) return;
      a.href = targets[key];
      if (key !== 'email') { a.target = '_blank'; a.rel = 'noopener'; }
    });
  }
})();
